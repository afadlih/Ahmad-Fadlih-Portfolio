import type { Language, LocalizedText } from "@/types/content";

export const languages: Language[] = ["id", "en"];

export function isLanguage(value: string): value is Language {
  return languages.includes(value as Language);
}

export function localize(value: LocalizedText, language: Language) {
  return value[language];
}

export function localePath(language: Language, path = "") {
  const normalized = path.startsWith("/") ? path : `/${path}`;
  return `/${language}${normalized === "/" ? "" : normalized}`;
}

